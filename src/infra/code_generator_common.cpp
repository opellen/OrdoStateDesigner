QString sanitizeIdentifier(const QString& raw, bool capitalizeFirst) {
    QString cleaned = raw;
    cleaned.replace(QLatin1Char('*'), QStringLiteral("Wildcard"));
    static const QRegularExpression boundary(QStringLiteral("[^A-Za-z0-9]+"));
    const QStringList tokens = cleaned.split(boundary, Qt::SkipEmptyParts);
    QString result;
    for (int i = 0; i < tokens.size(); ++i) {
        QString token = tokens.at(i);
        // Lowercase all-caps words so "SESSION_COMMITTED" joins as "sessionCommitted".
        bool hasLetter = false;
        bool allLettersUpper = true;
        for (const QChar& c : token) {
            if (c.isLetter()) {
                hasLetter = true;
                if (!c.isUpper()) {
                    allLettersUpper = false;
                    break;
                }
            }
        }
        if (hasLetter && allLettersUpper) {
            token = token.toLower();
        }

        if (i == 0 && !capitalizeFirst) {
            token[0] = token.at(0).toLower();
        } else {
            token[0] = token.at(0).toUpper();
        }
        result += token;
    }
    if (!result.isEmpty() && result.at(0).isDigit()) {
        result.prepend(QLatin1Char('_'));
    }
    return result;
}

QString sanitizeSnakeCase(const QString& raw) {
    QString cleaned = raw;
    cleaned.replace(QLatin1Char('*'), QStringLiteral("wildcard"));
    static const QRegularExpression boundary(QStringLiteral("[^A-Za-z0-9]+"));
    const QStringList tokens = cleaned.split(boundary, Qt::SkipEmptyParts);
    QStringList lowered;
    lowered.reserve(tokens.size());
    for (const QString& token : tokens) {
        lowered.push_back(token.toLower());
    }
    QString result = lowered.join(QStringLiteral("_"));
    if (!result.isEmpty() && result.at(0).isDigit()) {
        result.prepend(QLatin1Char('_'));
    }
    return result;
}


