QString contextTypeSpelling(ContextType type) {
    switch (type) {
        case ContextType::Bool:
            return QStringLiteral("bool");
        case ContextType::Int:
            return QStringLiteral("long long");
        case ContextType::Double:
            return QStringLiteral("double");
        case ContextType::String:
            return QStringLiteral("std::string");
        case ContextType::Object:
            return QStringLiteral("/* object */");
    }
    return QStringLiteral("long long");
}

QString cppPayloadTypeSpelling(const QString& payloadType) {
    if (const auto scalar = builtInPayloadScalar(payloadType)) {
        return contextTypeSpelling(*scalar);
    }
    return payloadType.trimmed();
}

// The C++ type `event` binds to in this row's guard and action, or empty. Per
// ROW from its payloadType, the same rule as the simulator and validator; an
// onDone/onError row binds `output`/`error` instead, never `event`.
QString eventPayloadCppTypeForTransition(const Machine& machine, const Transition& transition) {
    if (transition.payloadType.isEmpty() ||
        invokePayloadKindForTransition(machine, transition) != InvokePayloadKind::None) {
        return QString();
    }
    return cppPayloadTypeSpelling(transition.payloadType);
}

void emitNestedStruct(QString& out, const QJsonObject& obj, const QString& structTypeName,
                      const QString& memberName, int indentLevel) {
    const QString indent(indentLevel * 4, QLatin1Char(' '));
    const QString innerIndent((indentLevel + 1) * 4, QLatin1Char(' '));
    out += indent + QStringLiteral("struct %1 {\n").arg(structTypeName);

    QStringList keys = obj.keys();
    std::sort(keys.begin(), keys.end());

    for (const QString& key : keys) {
        const QJsonValue val = obj.value(key);
        if (val.isBool()) {
            out += innerIndent + QStringLiteral("bool %1 = %2;\n")
                       .arg(key, val.toBool() ? QStringLiteral("true") : QStringLiteral("false"));
        } else if (val.isDouble()) {
            const double num = val.toDouble();
            const bool isInt = std::isfinite(num) && num == std::trunc(num) && std::fabs(num) < 9.2e18;
            if (isInt) {
                out += innerIndent + QStringLiteral("long long %1 = %2;\n")
                           .arg(key, QString::number(static_cast<qint64>(num)));
            } else {
                out += innerIndent + QStringLiteral("double %1 = %2;\n").arg(key, cppDoubleLiteral(num));
            }
        } else if (val.isString()) {
            QString escaped;
            const QString str = val.toString();
            for (const QChar ch : str) {
                const char16_t unit = ch.unicode();
                if (unit == u'\\') {
                    escaped += QLatin1String("\\\\");
                } else if (unit == u'"') {
                    escaped += QLatin1String("\\\"");
                } else if (unit < 0x20 || unit == 0x7f) {
                    escaped += QStringLiteral("\\%1").arg(static_cast<int>(unit), 3, 8, QLatin1Char('0'));
                } else {
                    escaped += ch;
                }
            }
            out += innerIndent + QStringLiteral("std::string %1 = \"%2\";\n").arg(key, escaped);
        } else if (val.isObject()) {
            const QString subStructType = sanitizeIdentifier(key, true) + QStringLiteral("_t");
            emitNestedStruct(out, val.toObject(), subStructType, key, indentLevel + 1);
        }
    }
    out += indent + QStringLiteral("} %1;\n").arg(memberName);
}

// Shortest text that re-parses to the same double, always with a '.' or
// exponent so C++ reads a double (mirrors expr's printDouble()).
QString cppDoubleLiteral(double value) {
    QString text = QString::number(value, 'g', 17);
    for (int precision = 1; precision < 17; ++precision) {
        const QString candidate = QString::number(value, 'g', precision);
        if (candidate.toDouble() == value) {
            text = candidate;
            break;
        }
    }
    if (!text.contains(QLatin1Char('.')) && !text.contains(QLatin1Char('e')) && !text.contains(QLatin1Char('E'))) {
        text.append(QLatin1String(".0"));
    }
    return text;
}

// C++ initialiser for a context variable. Must match the simulator's seeding
// exactly (sim_agent.h), or the generated core starts from a different state:
// Bool "true"/"false" case-insensitive, Int/Double trimmed, String verbatim,
// malformed or non-finite -> the type's zero value. INT64_MIN is spelled as
// two terms: `-9223372036854775808` negates an out-of-range literal.
QString contextInitialiser(const ContextVariable& variable) {
    const QString trimmed = variable.initialValue.trimmed();
    switch (variable.type) {
        case ContextType::Bool:
            return trimmed.compare(QStringLiteral("true"), Qt::CaseInsensitive) == 0 ? QStringLiteral("true")
                                                                                      : QStringLiteral("false");
        case ContextType::Int: {
            bool ok = false;
            const qint64 parsed = trimmed.toLongLong(&ok);
            if (!ok) {
                return QStringLiteral("0");
            }
            if (parsed == std::numeric_limits<qint64>::min()) {
                return QStringLiteral("(-9223372036854775807LL - 1)");
            }
            return QString::number(parsed);
        }
        case ContextType::Double: {
            bool ok = false;
            const double parsed = trimmed.toDouble(&ok);
            if (!ok || !std::isfinite(parsed)) {
                return QStringLiteral("0.0");
            }
            return cppDoubleLiteral(parsed);
        }
        case ContextType::String:
            // Octal escapes, never \x: \x is greedy and would swallow a
            // following hex digit of the text.
            {
                QString out;
                for (const QChar ch : variable.initialValue) {
                    const char16_t unit = ch.unicode();
                    if (unit == u'\\') {
                        out += QLatin1String("\\\\");
                    } else if (unit == u'"') {
                        out += QLatin1String("\\\"");
                    } else if (unit < 0x20 || unit == 0x7f) {
                        out += QStringLiteral("\\%1").arg(static_cast<int>(unit), 3, 8, QLatin1Char('0'));
                    } else {
                        out += ch;
                    }
                }
                return QLatin1Char('"') + out + QLatin1Char('"');
            }
    }
    return QStringLiteral("0");
}


const State* findStateById(const Machine& machine, quint64 id) {
    for (const State& state : machine.states) {
        if (state.id == id) {
            return &state;
        }
    }
    return nullptr;
}

quint64 parentIdOf(const Machine& machine, quint64 stateId) {
    if (stateId == 0) {
        return 0;
    }
    const State* state = findStateById(machine, stateId);
    return state ? state->parentId : 0;
}

bool isAncestorId(const Machine& machine, quint64 ancestorId, quint64 descendantId) {
    if (ancestorId == 0) {
        return true;
    }
    quint64 cur = descendantId;
    while (cur != 0) {
        const quint64 parent = parentIdOf(machine, cur);
        if (parent == ancestorId) {
            return true;
        }
        cur = parent;
    }
    return false;
}

quint64 lccaId(const Machine& machine, quint64 sourceId, quint64 targetId) {
    quint64 anc = parentIdOf(machine, sourceId);
    while (!isAncestorId(machine, anc, targetId)) {
        anc = parentIdOf(machine, anc);
    }
    return anc;
}

quint64 lccaId(const Machine& machine, quint64 sourceId, const QList<quint64>& targetIds) {
    if (targetIds.isEmpty()) {
        return 0;
    }
    quint64 anc = lccaId(machine, sourceId, targetIds.first());
    for (int i = 1; i < targetIds.size(); ++i) {
        while (!isAncestorId(machine, anc, targetIds.at(i))) {
            anc = parentIdOf(machine, anc);
        }
    }
    return anc;
}

int depthOfId(const Machine& machine, quint64 stateId) {
    int depth = 0;
    quint64 cur = parentIdOf(machine, stateId);
    while (cur != 0) {
        ++depth;
        cur = parentIdOf(machine, cur);
    }
    return depth;
}



