// ---- guard / action classification and emission ----------------------------
// Classification always goes through expr's isBareIdentifier()/parse*Form(),
// the same functions the validator and simulator use; never mirror the rules.

// True when `guard` becomes a pure-virtual hook rather than inline code: a bare
// identifier always does; an expression does only when there is neither a
// Context nor a payload (`payloadInScope`) to compile it against.


bool guardIsHook(const GenModel& model, const QString& guard, bool payloadInScope) {
    if (expr::isBareIdentifier(guard)) {
        return true;
    }
    return payloadInScope ? false : !model.hasContext;
}

// An action is a hook only when no action form (sendTo, sendParent, raise,
// assign) claims it, valid or malformed.
bool actionIsHook(const GenModel& model, const QString& action, bool payloadInScope) {
    const expr::SendToForm sendToForm = expr::parseSendToForm(action);
    if (sendToForm.ok || !sendToForm.message.isEmpty()) {
        return false;
    }
    const expr::SendParentForm sendParentForm = expr::parseSendParentForm(action);
    if (sendParentForm.ok || !sendParentForm.message.isEmpty()) {
        return false;
    }
    const expr::RaiseForm raiseForm = expr::parseRaiseForm(action);
    if (raiseForm.ok || !raiseForm.message.isEmpty()) {
        return false;
    }
    if (!payloadInScope && !model.hasContext) {
        return true;
    }
    const expr::AssignForm form = expr::parseAssignForm(action);
    return !form.ok && form.message.isEmpty();
}

QString eventEnumIdent(const GenModel& model, const QString& rawEvent) {
    if (model.eventEnumIdentByRaw.contains(rawEvent)) {
        return model.eventEnumIdentByRaw.value(rawEvent);
    }
    for (const QString& existing : model.eventOrder) {
        if (existing.compare(rawEvent, Qt::CaseInsensitive) == 0) {
            return model.eventEnumIdentByRaw.value(existing);
        }
    }
    return sanitizeIdentifier(rawEvent, true);
}

// The C++ condition for a trimmed, non-blank guard, optionally negated.
// `bareIdentifiers` names the row's payload parameter ("output", "error" or
// "event"), if any; non-empty also means the payload is in scope.
QString guardCondition(const GenModel& model, const QString& guard, bool negated,
                        const QSet<QString>& bareIdentifiers) {
    const QString prefix = negated ? QStringLiteral("!") : QString();
    if (guardIsHook(model, guard, !bareIdentifiers.isEmpty())) {
        return prefix + QStringLiteral("guards_.get().%1(%2)")
                            .arg(model.guards.idOf(guard),
                                 model.hasContext ? QLatin1String(kContextMember) : QLatin1String(""));
    }
    const expr::ParseResult parsed = expr::parse(guard);
    if (!parsed.ok) {
        // An unparseable guard is false, as in the simulator.
        return negated ? QStringLiteral("true") : QStringLiteral("false");
    }
    const QString emitted = expr::emitCpp(parsed.ast, QLatin1String(kContextMember), bareIdentifiers);
    return negated ? QStringLiteral("!(%1)").arg(emitted) : emitted;
}

// The one statement an action becomes, or empty for "emit nothing": a
// malformed form, an unknown assign target or an unparseable RHS (validator
// errors the simulator also skips). `bareIdentifiers` as in guardCondition().
QString actionStatement(const GenModel& model, const QString& action, const QSet<QString>& bareIdentifiers) {
    const expr::SendToForm sendToForm = expr::parseSendToForm(action);
    if (sendToForm.ok) {
        return QStringLiteral("actions_.get().%1(%2);")
            .arg(model.actions.idOf(action),
                 model.hasContext ? QLatin1String(kContextMember) : QLatin1String(""));
    }
    if (!sendToForm.message.isEmpty()) {
        return QString();
    }
    const expr::SendParentForm sendParentForm = expr::parseSendParentForm(action);
    if (sendParentForm.ok) {
        return QStringLiteral("actions_.get().%1(%2);")
            .arg(model.actions.idOf(action),
                 model.hasContext ? QLatin1String(kContextMember) : QLatin1String(""));
    }
    if (!sendParentForm.message.isEmpty()) {
        return QString();
    }
    if (actionIsHook(model, action, !bareIdentifiers.isEmpty())) {
        return QStringLiteral("actions_.get().%1(%2);")
            .arg(model.actions.idOf(action),
                 model.hasContext ? QLatin1String(kContextMember) : QLatin1String(""));
    }
    const expr::RaiseForm raiseForm = expr::parseRaiseForm(action);
    if (raiseForm.ok) {
        return QStringLiteral("raise(Event::%1);").arg(eventEnumIdent(model, raiseForm.event));
    }
    if (!raiseForm.message.isEmpty()) {
        return QString();  // malformed raise
    }
    const expr::AssignForm form = expr::parseAssignForm(action);
    if (!form.ok) {
        return QString();  // malformed assign
    }
    const ContextVariable* target = nullptr;
    const QString rootName = form.rootTarget();
    for (const ContextVariable& variable : model.context) {
        if (variable.name == rootName) {
            target = &variable;
            break;
        }
    }
    if (target == nullptr) {
        return QString();
    }
    const expr::ParseResult rhs = expr::parse(form.valueSource);
    if (!rhs.ok) {
        return QString();
    }
    const QString value = expr::emitCpp(rhs.ast, QLatin1String(kContextMember), bareIdentifiers);

    if (!form.isMemberAssign()) {
        switch (target->type) {
            case ContextType::Int:
                // Always cast: matches the simulator's truncation of a Double
                // RHS without inferring the RHS type here.
                return QStringLiteral("%1.%2 = static_cast<long long>(%3);")
                    .arg(QLatin1String(kContextMember), target->name, value);
            case ContextType::Double:
                // Matches the simulator's Int -> Double promotion.
                return QStringLiteral("%1.%2 = static_cast<double>(%3);")
                    .arg(QLatin1String(kContextMember), target->name, value);
            case ContextType::Bool:
            case ContextType::String:
            case ContextType::Object:
                // No coercion: a type mismatch is a validator error and should
                // fail to compile rather than be dropped silently.
                return QStringLiteral("%1.%2 = %3;").arg(QLatin1String(kContextMember), target->name, value);
        }
        return QString();
    }

    // Member assign (e.g. user.age = 25 or user.profile.score = 99.5)
    QJsonParseError err;
    const QJsonDocument jsonDoc = QJsonDocument::fromJson(target->initialValue.trimmed().toUtf8(), &err);
    bool isInt = false;
    bool isDouble = false;
    if (!jsonDoc.isNull() && jsonDoc.isObject()) {
        const QStringList segments = form.memberPath().split(QLatin1Char('.'));
        QJsonObject curr = jsonDoc.object();
        for (int i = 0; i < segments.size(); ++i) {
            const QString& seg = segments.at(i);
            if (!curr.contains(seg)) break;
            const QJsonValue v = curr.value(seg);
            if (i == segments.size() - 1) {
                if (v.isDouble()) {
                    const double num = v.toDouble();
                    isInt = std::isfinite(num) && num == std::trunc(num) && std::fabs(num) < 9.2e18;
                    isDouble = !isInt;
                }
            } else if (v.isObject()) {
                curr = v.toObject();
            } else {
                break;
            }
        }
    }

    if (isInt) {
        return QStringLiteral("%1.%2 = static_cast<long long>(%3);")
            .arg(QLatin1String(kContextMember), form.target, value);
    }
    if (isDouble) {
        return QStringLiteral("%1.%2 = static_cast<double>(%3);")
            .arg(QLatin1String(kContextMember), form.target, value);
    }
    return QStringLiteral("%1.%2 = %3;").arg(QLatin1String(kContextMember), form.target, value);
}

// Appends one action's statement at `indent`, or nothing when it emits nothing.
void appendAction(QString& text, const GenModel& model, const QString& indent, const QString& action,
                   const QSet<QString>& bareIdentifiers) {
    const QString statement = actionStatement(model, action, bareIdentifiers);
    if (!statement.isEmpty()) {
        text += indent + statement + QStringLiteral("\n");
    }
}

