GenModel buildModel(const Machine& machine, const QString& rootNamespace) {
    GenModel model;
    model.machineNs = sanitizeSnakeCase(machine.name);
    model.machinePascal = sanitizeIdentifier(machine.name, true);
    // First: the hook-collection loops below read hasContext.
    model.context = machine.context;
    model.hasContext = !machine.context.isEmpty();
    model.hasTypes = !machine.types.isEmpty() || !machine.externalHeaders.isEmpty();
    for (const ContextVariable& variable : machine.context) {
        model.hasStringContext = model.hasStringContext || variable.type == ContextType::String || variable.type == ContextType::Object;
    }

    // Before the transitions loop, which needs the invoke maps.
    for (const State& state : machine.states) {
        const auto invocations = state.effectiveInvocations();
        if (invocations.isEmpty()) {
            continue;
        }
        model.hasInvoke = true;
        QStringList effIds;
        for (const Invocation& inv : invocations) {
            const QString effId = effectiveInvocationId(inv);
            if (effId.isEmpty()) {
                continue;
            }
            effIds.push_back(effId);
            if (!model.invokeOutputTypeByEffectiveId.contains(effId)) {
                // First declaration wins, including its output type.
                model.invokeIdOrder.push_back(effId);
                model.invokeOutputTypeByEffectiveId.insert(effId, inv.outputType);
            }
        }
        if (!effIds.isEmpty()) {
            model.invokeEffectiveIdByStateId.insert(state.id, effIds.first());
            model.invokeEffectiveIdsByStateId.insert(state.id, effIds);
        }
    }

    QStringList nsParts;
    for (const QString& part : rootNamespace.split(QStringLiteral("::"), Qt::SkipEmptyParts)) {
        nsParts.push_back(part);
    }
    if (!model.machineNs.isEmpty()) {
        nsParts.push_back(model.machineNs);
    }
    if (nsParts.isEmpty()) {
        // Never emit an anonymous namespace; the validator blocks this case
        // from reaching disk anyway.
        nsParts.push_back(QStringLiteral("generated_machine"));
    }
    model.nsJoined = nsParts.join(QStringLiteral("::"));

    QString firstStateIdent;
    QString initialIdent;
    for (const State& state : machine.states) {
        const QString ident = sanitizeIdentifier(state.name, true);
        model.stateIdentById.insert(state.id, ident);
        if (firstStateIdent.isEmpty()) {
            firstStateIdent = ident;
        }
        if (state.id == machine.initialStateId) {
            initialIdent = ident;
        }
    }
    // The first-state fallback only matters for an invalid machine.
    model.defaultStateIdent = !initialIdent.isEmpty() ? initialIdent : firstStateIdent;

    for (const Transition& transition : machine.transitions) {
        const QString event = transition.event.trimmed();
        // onDone/onError rows are recognised structurally, never by event
        // text, and kept out of the public event vocabulary.
        const InvokePayloadKind payloadKind = invokePayloadKindForTransition(machine, transition);
        const bool hasEventPayload = !eventPayloadCppTypeForTransition(machine, transition).isEmpty();
        if (payloadKind == InvokePayloadKind::None) {
            if (!event.isEmpty()) {
                if (!model.eventTransitions.contains(event)) {
                    model.eventOrder.push_back(event);
                    model.eventStructNameByRaw.insert(event, sanitizeIdentifier(event, true) + QStringLiteral("Requested"));
                    model.eventMethodByRaw.insert(event, sanitizeIdentifier(event, false) + QStringLiteral("Requested"));
                }
                model.eventTransitions[event].push_back(&transition);
                if (hasEventPayload && !model.eventPayloadTypeByRaw.contains(event)) {
                    model.eventPayloadTypeByRaw.insert(event, transition.payloadType);
                }
            }
        } else if (payloadKind == InvokePayloadKind::Output) {
            model.onDoneByState[transition.from].push_back(&transition);
        } else {
            model.onErrorByState[transition.from].push_back(&transition);
        }
        // Every transition's guard, blank-event (delayed) ones included, but
        // only hook guards; expression guards compile inline.
        const bool payloadInScope = (payloadKind != InvokePayloadKind::None) || hasEventPayload;
        if (guardIsHook(model, transition.guard, payloadInScope)) {
            model.guards.add(transition.guard);
        }
    }
    const auto collectAction = [&](const QString& action, bool payloadInScope = false) {
        const expr::SendToForm sendToForm = expr::parseSendToForm(action);
        if (sendToForm.ok) {
            model.actions.addCustom(action, QStringLiteral("sendTo_%1_%2").arg(sendToForm.target, sendToForm.event));
            return;
        }
        const expr::SendParentForm sendParentForm = expr::parseSendParentForm(action);
        if (sendParentForm.ok) {
            model.actions.addCustom(action, QStringLiteral("sendParent_%1").arg(sendParentForm.event));
            return;
        }
        if (actionIsHook(model, action, payloadInScope)) {
            model.actions.add(action);
        }
    };

    for (const Transition& transition : machine.transitions) {
        const bool payloadInScope = (invokePayloadKindForTransition(machine, transition) != InvokePayloadKind::None) ||
                                    !eventPayloadCppTypeForTransition(machine, transition).isEmpty();
        collectAction(transition.action, payloadInScope);
    }
    for (const State& state : machine.states) {
        for (const QString& entryAction : state.entryActions) {
            collectAction(entryAction);
        }
        for (const QString& exitAction : state.exitActions) {
            collectAction(exitAction);
        }
    }

    for (const Transition& transition : machine.transitions) {
        const auto tt = expr::parseTimeTrigger(transition.event);
        if (tt.ok || (transition.event.trimmed().isEmpty() && transition.delayMs > 0)) {
            model.delayedBySource[transition.from].push_back(&transition);
            model.hasScheduler = true;
        }
    }

    for (const Transition& transition : machine.transitions) {
        if (transition.isAlways()) {
            model.hasAlways = true;
            model.alwaysTransitions.push_back(&transition);
        }
    }

    const auto checkRaise = [&](const QString& action) {
        const expr::RaiseForm form = expr::parseRaiseForm(action);
        if (form.ok) {
            model.hasRaise = true;
            bool found = false;
            for (const QString& existing : model.eventOrder) {
                if (existing.compare(form.event, Qt::CaseInsensitive) == 0) {
                    found = true;
                    break;
                }
            }
            if (!found) {
                model.eventOrder.push_back(form.event);
                model.eventStructNameByRaw.insert(form.event, sanitizeIdentifier(form.event, true) + QStringLiteral("Requested"));
                model.eventMethodByRaw.insert(form.event, sanitizeIdentifier(form.event, false) + QStringLiteral("Requested"));
            }
        }
    };
    for (const Transition& transition : machine.transitions) {
        checkRaise(transition.action);
    }
    for (const State& state : machine.states) {
        for (const QString& act : state.entryActions) {
            checkRaise(act);
        }
        for (const QString& act : state.exitActions) {
            checkRaise(act);
        }
    }
    for (const QString& rawEvent : model.eventOrder) {
        model.eventEnumIdentByRaw.insert(rawEvent, sanitizeIdentifier(rawEvent, true));
    }

    // ---- hierarchical topology (always built) --------------------------------
    for (int i = 0; i < machine.states.size(); ++i) {
        model.stateIndexById.insert(machine.states[i].id, i);
    }
    const auto indexOfId = [&model](quint64 id) -> int {
        return id == 0 ? -1 : model.stateIndexById.value(id, -1);
    };
    model.hierStates.reserve(machine.states.size());
    for (const State& state : machine.states) {
        HierState hs;
        hs.parentIndex = indexOfId(state.parentId);
        hs.depth = depthOfId(machine, state.id);
        hs.initialChildIndex = indexOfId(state.initialChildId);
        hs.isParallel = (state.kind == StateKind::Parallel);
        model.hierStates.push_back(hs);
    }
    model.hierTransitions.reserve(machine.transitions.size());
    for (const Transition& transition : machine.transitions) {
        HierTransition ht;
        ht.sourceIndex = indexOfId(transition.from);
        ht.declaredTargetIndex = indexOfId(transition.to);
        ht.reenter = transition.reenter;
        ht.always = transition.isAlways();
        ht.isMultiTarget = transition.isMultiTarget();
        if (transition.isMultiTarget()) {
            model.hasMultiTarget = true;
            for (quint64 tid : transition.targets) {
                ht.targetIndices.push_back(indexOfId(tid));
            }
            ht.targetIndex = ht.targetIndices.isEmpty() ? -1 : ht.targetIndices.first();
            ht.lccaIndex = indexOfId(lccaId(machine, transition.from, transition.targets));
            ht.historyPolicy = HierHistoryRedirect::None;
        } else if (transition.to != 0) {
            // A History target enters through its parent compound (static
            // topology; the validator guarantees the parent exists).
            quint64 effectiveTargetId = transition.to;
            HierHistoryRedirect policy = HierHistoryRedirect::None;
            const State* dest = findStateById(machine, transition.to);
            if (dest && dest->kind == StateKind::History) {
                effectiveTargetId = dest->parentId;
                policy = dest->historyDeep ? HierHistoryRedirect::AllLevels : HierHistoryRedirect::OneLevel;
            }
            ht.targetIndex = indexOfId(effectiveTargetId);
            ht.lccaIndex = indexOfId(lccaId(machine, transition.from, effectiveTargetId));
            ht.historyPolicy = policy;
        }
        model.hierTransitions.push_back(ht);
    }
    // Same first-state fallback as defaultStateIdent, as an index.
    int initialIndex = -1;
    for (int i = 0; i < machine.states.size(); ++i) {
        if (machine.states[i].id == machine.initialStateId) {
            initialIndex = i;
            break;
        }
    }
    model.initialStateIndex = (initialIndex != -1) ? initialIndex : (machine.states.isEmpty() ? -1 : 0);

    return model;
}



QString stateIdent(const GenModel& model, quint64 stateId) {
    return model.stateIdentById.value(stateId, QStringLiteral("Unknown"));
}

